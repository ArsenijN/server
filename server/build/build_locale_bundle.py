#!/usr/bin/env python3
"""
build_locale_bundle.py — bundle locale JSON files into a single JS file
=======================================================================
Usage:
    python3 build_locale_bundle.py                    # reads ./locale/, writes ./fd_locale_bundle.js
    python3 build_locale_bundle.py locale/ out.js     # custom paths

Run this whenever you edit en.json, uk.json, or add a new locale file.
The generated fd_locale_bundle.js must be deployed alongside fd_addons.js.

The bundle defines window._FD_LOCALES synchronously so fd_addons.js can
initialise t() before any render functions run — eliminating the async
race condition where t('key') returned the bare key string.
"""
import json
import pathlib
import sys
from datetime import datetime, timezone

def build(locale_dir: pathlib.Path, output: pathlib.Path):
    locale_dir = locale_dir.resolve()
    if not locale_dir.is_dir():
        print(f'ERROR: locale directory not found: {locale_dir}')
        sys.exit(1)

    locales = {}
    for jf in sorted(locale_dir.glob('*.json')):
        lang = jf.stem
        with open(jf, encoding='utf-8') as f:
            data = json.load(f)
        # Skip the _meta key from the bundle to keep it lean;
        # fd_addons.js only needs the translatable string pairs.
        locales[lang] = {k: v for k, v in data.items() if k != '_meta'}
        print(f'  Bundled {lang}.json ({len(locales[lang])} keys)')

    ts  = datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
    out = json.dumps(locales, ensure_ascii=False, separators=(',', ':'))

    bundle = f"""// fd_locale_bundle.js — AUTO-GENERATED by build_locale_bundle.py
// Generated: {ts}
// DO NOT EDIT directly. Edit locale/*.json then re-run build_locale_bundle.py.
//
// Why this file exists:
//   fd_addons.js loads locale JSON via fetch(), which is asynchronous.
//   If script.js calls t() before the fetch resolves, t() returns the bare
//   key string (e.g. "welcome_text") instead of the translated value.
//   This bundle is loaded synchronously via a plain <script> tag BEFORE
//   fd_addons.js, so window._FD_LOCALES is populated before any t() call.
//
// Include order in index.html:
//   <script src="/fluxdrop_pp/fd_locale_bundle.js"></script>  ← this file
//   <script src="/fluxdrop_pp/fd_addons.js"></script>
//   (script.js order relative to these two does not matter)

window._FD_LOCALES = {out};
"""
    output.parent.mkdir(parents=True, exist_ok=True)
    with open(output, 'w', encoding='utf-8') as f:
        f.write(bundle)
    print(f'  Written {output} ({output.stat().st_size // 1024} KB)')

if __name__ == '__main__':
    locale_dir = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path('locale')
    out_path   = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else pathlib.Path('fd_locale_bundle.js')
    print(f'Building locale bundle from {locale_dir}/ → {out_path}')
    build(locale_dir, out_path)
    print('Done.')
